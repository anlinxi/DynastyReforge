/**
 * 画面层次的**唯一出处**。
 *
 * ## 为什么必须集中
 *
 * 场上精灵的深度**就是它在地图上的 y**（`FieldSprite` / `occlusion.js`），
 * 而地图最高的一张是 `MP1101` 沙州城 **2640**。于是任何写死的层号只要低于
 * 地图高度，在高的那几张图上就会被人物盖住 —— 而且**一点都不报错**。
 *
 * 2026-09-13 盘了一遍，原先的层号全在 2640 以下，实际后果：
 *
 * | 层 | 原值 | 在哪张图上出事 |
 * |---|---|---|
 * | 购物界面 | 1200 | **9 张图**（高 >2000 的那些）里站得靠下的 NPC 会盖住整个店面板 |
 * | 网点虚影 | 1500 | `MP1101` 屋顶（y=2150）压在虚影上面 —— **人被挡住了却看不见网点** |
 * | 过场精灵 / HUD | 2000 | 同上 |
 * | 对话立绘 / 对话框 | 2050 / 2100 | **4 张图**有对象 `y > 2050`，站那儿的人会**盖住对话框** |
 *
 * 现在一律排在 `SPRITE_MAX` 之上，而且**只在这一个文件里写死**。
 *
 * ⚠️ **加新层要加在这里**，不要在别处写数字 —— 判据表里「改共享常量先 grep
 * 全部消费者」那条的另一面：先集中，才谈得上 grep。
 */

/**
 * 场上精灵深度的上限 = **全库最高的那张地图**。
 *
 * 实测：`MP1101` 2640 是最高的，第二是 `MP1703`/`MP1013` 的 2400。
 * 取 2640 而不是取整，是为了这个数一看就知道出处；
 * 真要多出一张更高的图，`tools/tests/test_depths.py` 会红。
 */
export const SPRITE_MAX = 2640;

/** 画面层次。**数越大越靠前。** */
const DEPTH = Object.freeze({
  /** 地面美术。 */
  GROUND: 0,

  // —— 这中间是场上精灵：深度 = 它在地图上的 y，0 ~ SPRITE_MAX ——
  // 遮挡覆盖层是 y + 0.5（见 occlusion.js），仍在这个区间里。

  /**
   * 被挡住的人的**网点虚影**（`ghost.js`）。
   * 必须压过一切地图美术与遮挡物，但要低于所有界面 —— 店面板、菜单开着的
   * 时候，一个网点小人浮在面板上是错的。
   */
  GHOST: 2700,

  /** 购物界面（整屏面板）。 */
  SHOP: 2800,

  /** 剧情里 `topmost` 的过场精灵，与 HUD 同层（原作也是演出压住一切场景）。 */
  CUTSCENE: 3500,
  /** 左上角图号坐标 + 底部提示行。 */
  HUD: 3500,

  /** 对话立绘。 */
  PORTRAIT: 3550,
  /** 对话框本体（压住立绘的边）。 */
  DIALOGUE: 3600,

  /** 八页菜单（整屏面板）。 */
  MENU: 4500,
  /** 客栈盖住地图、低于行囊；进入时暂停显示剧情黑幕。 */
  INN: 4400,
  /**
   * 黑幕。它出场就意味着「这一场结束了」，**连对话框都不该再露出来**。
   */
  CURTAIN: 4500,

  /** 调试/兜底用的最上层。 */
  TOP: 9999,
});

export default DEPTH;
