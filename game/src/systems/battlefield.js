/**
 * 战场格盘 —— 八格阵型的几何。
 *
 * ## 这些数不是调出来的，是量出来的
 *
 * 战斗地面 `FLR000` 的**第 2 帧**是一张格线图（第 0 帧才是那块石板地）。
 * 对它做连通域标记，得到 28 个面积完全相同的菱形格：
 *
 * ```
 * u:      0     1   |   2     3     4   |   5     6
 * v=0    敌   敌   |  空   空   空   |  我   我
 * v=1    敌   敌   |  空   空   空   |  我   我
 * v=2    敌   敌   |  空   空   空   |  我   我
 * v=3    敌   敌   |  空   空   空   |  我   我
 * ```
 *
 * * 格心步长 **(±54, +27)**（菱形 108×54）。
 *   ⚠️ 不是 SF2 头里那个 `tile:[64,48]` —— 那是**图片存储的分块尺寸**，
 *   与游戏格盘无关，`counts.tiles = 494` 数的也是存储块。
 * * 两端各 **2 列 × 4 排 = 8 格**，正好是遇敌组的 `位置 0~7`；
 *   8 人的遇敌组（全库 4 条）正好填满，这是最硬的旁证。
 * * 中间 **3 列**空地，对应绝学「攻击位置」枚举里的
 *   **目标前面一行 / 二行 / 三行**（exe 规格 `0x3ef2a8`）。三行不多不少。
 *
 * ## `位置 0~7` 怎么对到格子
 *
 * exe 规格区**没有**这个枚举（编辑器是画了个格子让人点的）。
 * 判据来自配套资料 `…7－战利品和遇敌群组.txt`：它把【敌人阵容】直接印成
 * 一张 2 行 × 4 列的方格图，那就是 SuperCastleEdit 对 `位置` 的可视化。
 *
 * 拿**同一版本**（300 块 MOD）的 `LayoutTeam.ENC` 与那份 txt 交叉验证
 * 四种可能的映射，在 68 条无歧义样本上：
 *
 * | 假设 | 吻合 |
 * |---|---|
 * | 行=p//4、列=p%4 | 35.3% |
 * | 行倒置 | 35.3% |
 * | **列倒置 `p = 排×4 + (3−列)`** | **86.8%** |
 * | 行列都倒置 | 30.9% |
 *
 * 即**一排之内是从右往左数的**：
 *
 * ```
 * 后排（远）   位置 3  2  1  0
 * 前排（近）   位置 7  6  5  4
 * ```
 *
 * 旁证：全库单人遇敌组落在位置 6（37 次）与 7（21 次）最多，从不落 3、4 ——
 * 独自一个敌人站前排，符合常理。
 *
 * ## ⚠️ 还没有判据的一件事
 *
 * **一排四格在屏幕上从哪头数起**（txt 的「列 0」是等距的左上还是左下）。
 * 数据里找不到依据，这里取 `列 = v`。摆出来一眼能看出对错，
 * 错了把 {@link COLUMN_ORDER} 翻过来即可 —— 不要去改别处。
 */

/** 格盘尺寸：深度 7 列（敌 2 ＋ 空 3 ＋ 我 2）、宽度 4 排。 */
export const BOARD_DEPTH = 7;
export const BOARD_WIDTH = 4;

/** 等距格心步长。量自 `FLR000` 第 2 帧。 */
export const STEP_X = 54;
export const STEP_Y = 27;

/** `(u=0, v=0)` 那一格的格心屏幕坐标。 */
export const ORIGIN = Object.freeze({ x: 236, y: 189 });

/**
 * 每方各占的两列（下标 0 是**后排**，1 是**前排**；前排＝靠近对手那一列）。
 *
 * ⚠️ 我方查这张表要用 `1 − 排`，见 {@link slotToTile} 里的「点对称」那一段。
 */
export const FOE_DEPTHS = Object.freeze([0, 1]);
export const ALLY_DEPTHS = Object.freeze([6, 5]);

/**
 * 一排四格的排布方向。
 *
 * ## 判据：素材基准列 × 单敌分布
 *
 * exe 规格区**没有**格位枚举（编辑器是画格子让人点的），阵形页的
 * `MEN7002/7004` 是 16 张高亮图但全挂在同一个坐标 `(279,240)` 上
 * （位置由 exe 代码算，拿不到）。所以只能从别处推。
 *
 * 站立素材是按「**一个敌人单独出场时站的位置**」构图的，两方的基准点都
 * 落在 `v = 1` 这一列。那么这一列应当正是单敌最常站的那一列：
 *
 * | 取值 | 单敌落在 v=1 的比例 |
 * |---|---|
 * | **+1（v = 列）** | **43 / 70（61%）** |
 * | −1（v = 3−列） | 5 / 70（7%） |
 *
 * 只有 `+1` 说得通。
 *
 * ⚠️ 我一度按「配套资料那张方格图印的就是屏幕上的样子，所以印在最左边的
 * 那格＝屏幕最左」翻成了 −1 —— **那是推理不是判据，而且是错的**。
 * 战斗场景里按 H 仍可当场翻，方便日后对着原版复核。
 */
let columnOrder = 1;

/** 当前排布方向。 */
export const COLUMN_ORDER = () => columnOrder;

/** 翻转排布方向（调试用，见上）。@returns 翻转后的值 */
export function flipColumnOrder() {
  columnOrder = -columnOrder;
  return columnOrder;
}

/**
 * 站立素材的**基准站立点**（屏幕像素，不是格）。
 *
 * 原作每个动画文件都按「这个角色站在自己默认位置」的 640×480 构图画好，
 * 摆到别的格子要整体平移。基准点取**影子层的框中心** —— 影子是角色与
 * 地面的接触面，它的中心就是站立点。
 *
 * | 素材 | 影子层框 | 中心 |
 * |---|---|---|
 * | `STN1030` 西夏兵 | (268,243)-(331,275) | **(299,259)** |
 * | `STN0010` 夏侯仪 | (322,268)-(363,294) | **(342,281)** |
 * | `STN0030` 封铃笙 | (325,275)-(381,305) | (353,290) |
 *
 * ⚠️ **不要拿整帧不透明像素的底边当站立点。** 那是影子的**下沿**，
 * 比真正的站立点低十几个像素 —— 表现是所有人都悬在格子上方一点，
 * 而格心的标记正好落在影子屁股底下。这个错犯过一次。
 *
 * ⚠️ 同一方各素材的影子中心并不完全一致（夏侯仪与封铃笙差约 (11,9)，
 * 因为影子随贴图宽度变）。这里取代表素材，**残留误差约 10px**（格距 54px）。
 * 要彻底消掉得在 `export_pack.py` 里把站立点算好写进 `anim.json`，
 * 那是工具改动，记在 demo 计划的 TODO 里。
 */
export const ART_ANCHOR = Object.freeze({
  foe: Object.freeze({ x: 299, y: 259 }),
  ally: Object.freeze({ x: 342, y: 281 }),
});

/** 格 → 屏幕坐标（格心，也就是脚底落点）。 */
export function tileCenter(u, v) {
  return {
    x: ORIGIN.x + (u - v) * STEP_X,
    y: ORIGIN.y + (u + v) * STEP_Y,
  };
}

/**
 * 遇敌组 / 队伍的 `位置 0~7` → 格。
 *
 * ## ⭐ 两边的位置号约定不一样（2026-09-12 定）
 *
 * ```
 * 敌方：位置 0~3 → 后排（外侧 u=0）   一排之内 v = 3 − 位置%4
 * 我方：位置 0~3 → 前排（内侧 u=5）   一排之内 v =     位置%4
 * ```
 *
 * 也就是**排的数起点相反、列的方向也相反**。
 * ⚠️ 别把它想成「180° 点对称」—— 我一开始就是这么以为的，
 * 按点对称写出来的断言当场就红了（点对称会把我方 0~3 放到 u=6）。
 *
 * **判据**：用户给的原作阵形页截图 —— `Save009` 里霍雍的阵型格号是 **0**，
 * 而原作把他画在板的**右上端**（我方前排、最靠外那格）。
 * 我们原先把他画在左下角，正好差 180°。
 *
 * ⚠️ **上一版只镜像了「排」（靠 `ALLY_DEPTHS=[6,5]` 倒序），没镜像「列」。**
 * 成因是：关于列方向的两条判据（`LayoutTeam.ENC` × 配套资料 68 条 86.8%、
 * 单敌落 `v=1` 的 43/70）**全部来自遇敌组，也就是敌方数据**，
 * 我把敌方的约定原样套到了我方身上。
 *
 * ⚠️ 更要记住的是**上一轮的处理方式错了**：当时发现「菜单站左下、打起来站右上」，
 * 我把**菜单**转了 180° 去迁就战斗 —— 而菜单那边本来是对的。
 * 两处不一致时，先找哪一处有原作判据，不要挑好改的那处动。
 *
 * 旁证：`Save008` 里古伦德（命极 699、膂力 277 的肉盾）在位置 0 —— 修正后是**前排**；
 * 慕容璇玑（灵力 500 的法系）在位置 4 —— 修正后是**后排**。修正前正好反着。
 *
 * @param {number} slot 0~7
 * @param {'ally'|'foe'} side
 */
export function slotToTile(slot, side) {
  const s = Number(slot);
  if (!Number.isInteger(s) || s < 0 || s > 7) {
    throw new RangeError(`阵型位置只能是 0~7，收到 ${slot}`);
  }
  const rank = Math.floor(s / 4);           // 0 后排、1 前排（该方自己的视角）
  const column = 3 - (s % 4);               // 一排之内从右往左数
  const mine = side !== 'foe';
  // 我方两轴都翻 —— 见上面「点对称」。敌方一个字不动，那些判据都是拿它定的。
  const rankOnBoard = mine ? 1 - rank : rank;
  const columnOnBoard = mine ? BOARD_WIDTH - 1 - column : column;
  return {
    u: (mine ? ALLY_DEPTHS : FOE_DEPTHS)[rankOnBoard],
    v: columnOrder > 0 ? columnOnBoard : BOARD_WIDTH - 1 - columnOnBoard,
  };
}

/** 某格是不是这一方的阵地。中间三列谁都不占。 */
export function isHomeTile(u, side) {
  return (side === 'foe' ? FOE_DEPTHS : ALLY_DEPTHS).includes(u);
}

/**
 * 把站立素材从它自己的基准位搬到目标格要加的偏移。
 *
 * 这就是 `config.js` 里那对手调常数 `offsetX/offsetY` 的正解 ——
 * 以前是眼睛凑的（我方 +64/+58），现在按格心算。
 *
 * ## ⚠️ `anchor` 要传**这个包自己的**站立点（2026-09-17）
 *
 * 不传就退回 {@link ART_ANCHOR} 那一对**阵营代表值**，而各素材的贴图宽高不同、
 * 影子中心自然也不同 —— 实测我方 343~370（差 27px）、敌方 264~310（**差 46px**），
 * `STN2010` 赫蘭鐵罕比敌方代表值差 16px。后果是**人站在格子外面**：
 * 格盘叠层一开就看得见位置号在脚底下方几十像素（用户 2026-09-16 指出）。
 *
 * 每个包自己的站立点由 `tools/export_pack.py` 算好写在 `anim.json` 的
 * `stand_point` 里（＝**影子层的框中心**，⚠️ 不是整帧不透明像素的底边）。
 *
 * @param {number} slot 0~7
 * @param {'ally'|'foe'} side
 * @param {{x:number,y:number}} [anchor] 这一包自己的站立点；不给就用阵营代表值
 */
export function slotOffset(slot, side, anchor = null) {
  const tile = slotToTile(slot, side);
  const target = tileCenter(tile.u, tile.v);
  const base = anchor ?? ART_ANCHOR[side];
  return { x: target.x - base.x, y: target.y - base.y };
}

/** 单位绘制深度的起点。地面是 0，特效 500，提示 1000。 */
export const DEPTH_BASE = 10;

/**
 * 绘制深度：等距场景按屏幕 y 排序，靠下的盖住靠上的。
 *
 * ⚠️ **不能直接拿屏幕 y 当深度。** y 最大 432，乘个位次就到六位数，
 * 会一路盖过特效（500）、提示（1000）与状态面板。这里压进
 * `DEPTH_BASE … DEPTH_BASE+99` 这一段：`(u+v)` 定行、`(u−v)` 定同行内次序
 * （同一个 y 上确实会并排站两个，不定死次序的话每帧顺序会抖）。
 */
export function tileDepth(u, v) {
  return DEPTH_BASE + (u + v) * 10 + (u - v + BOARD_WIDTH);
}

/** 一方的八格，按绘制顺序（先画远的）排好。 */
export function formationTiles(side) {
  return Array.from({ length: 8 }, (_, slot) => {
    const tile = slotToTile(slot, side);
    return { slot, ...tile, ...tileCenter(tile.u, tile.v), depth: tileDepth(tile.u, tile.v) };
  }).sort((a, b) => a.depth - b.depth);
}

/**
 * 特效容器该放的偏移。
 *
 * ## 为什么不能直接用单位自己的站位偏移
 *
 * 特效素材（`effXXX.SF2`）的图层坐标是**按敌方基准点设计的落点** ——
 * `EFFA0010`（我方普攻命中）中心 (277,222) 就压在敌方基准位上。
 * 所以要把特效搬到某个目标身上，平移量得是
 * 「目标格心 − **敌方**基准点」，与目标属于哪一方无关。
 *
 * 用目标自己那一方的基准点会错 (43,22)：我方与敌方的基准点差这么多，
 * 于是打在我方身上的特效（比如闪避光效）整体偏出去一截。
 *
 * ## 这条也解掉了 `docs/专题/战斗.md` 里那条限制
 *
 * 那份文档写着「**敌方 offset 必须保持 0**，否则所有特效会一起脱靶」，
 * 并据此判定阵型做不了。真实情况是：当时不知道格盘在哪，所以任何移动
 * 都是瞎移。格心一旦拿到，按这个式子补偿即可，敌方随便站哪一格。
 */
export function effectOffset(tile) {
  if (!tile) return { x: 0, y: 0 };
  const { x, y } = tileCenter(tile.u, tile.v);
  return { x: x - ART_ANCHOR.foe.x, y: y - ART_ANCHOR.foe.y };
}
